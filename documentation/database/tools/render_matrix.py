"""Render generated/ENDPOINT_TABLE_MATRIX.md from generated/endpoints.json (+ other_writers.json)."""
import json, os, collections
HERE = os.path.dirname(os.path.abspath(__file__)); OUT = os.path.join(HERE, "../generated")
eps = json.load(open(os.path.join(OUT, "endpoints.json")))
other = json.load(open(os.path.join(OUT, "other_writers.json")))
cat = json.load(open(os.path.join(OUT, "catalog.json")))
AUTH = {"require_admin_api_key": "admin key", "get_current_student_id": "learner JWT", "require_staff": "staff cookie"}
def auth(e):
    a = [AUTH.get(x, x) for x in e["auth"]]
    return ", ".join(a) if a else "anonymous*"
def ops(e):
    by = collections.defaultdict(set)
    for t, o in e["ops"]: by[t].add(o)
    order = "CRUD"
    return "<br>".join(f"`{t}` {''.join(sorted(v, key=order.index))}" for t, v in sorted(by.items()))
seen = set(); rows = collections.defaultdict(list)
for e in eps:
    key = (e["method"], e["path"])
    if key in seen: continue
    seen.add(key)
    area = e["module"].split(".")[-1]
    rows[area].append(e)
L = ["# Generated: REST endpoint → table operations matrix", "",
     "Generated by [tools/render_matrix.py](../tools/render_matrix.py) from a **static** call-graph trace of",
     "`mathbank-rest` (route → handler → service functions → SQL strings). Letters: C=INSERT, R=SELECT,",
     "U=UPDATE/upsert, D=DELETE. Treat it as an index, not proof: dynamic SQL (`f\"knowledge.{table}\"`)",
     "is missed and shared helpers can over-attribute reads. The verified per-table mapping lives in",
     "each [schema document](../schemas/). `anonymous*` means no FastAPI auth dependency; some handlers",
     "check credentials in the body (e.g. login/register).", "",
     f"Endpoints: **{len(seen)}** unique method+path; tables/views in catalog: **{len(cat)}**.", ""]
for area in sorted(rows):
    L += [f"## `{area}`", "", "| Method | Path | Auth | Tables & ops |", "|---|---|---|---|"]
    for e in sorted(rows[area], key=lambda e: (e["path"], e["method"])):
        L.append(f"| {e['method']} | `{e['path']}` | {auth(e)} | {ops(e) or '—'} |")
    L.append("")
L += ["## Non-REST SQL users (ETL, workers, other services)", "", "| File | Tables & ops |", "|---|---|"]
for f in sorted(other):
    by = collections.defaultdict(set)
    for t, o in other[f]: by[t].add(o)
    L.append(f"| `{f}` | " + "<br>".join(f"`{t}` {''.join(sorted(v, key='CRUD'.index))}" for t, v in sorted(by.items())) + " |")
L.append("")
open(os.path.join(OUT, "ENDPOINT_TABLE_MATRIX.md"), "w").write("\n".join(L))
print("wrote", len(seen), "endpoints")
