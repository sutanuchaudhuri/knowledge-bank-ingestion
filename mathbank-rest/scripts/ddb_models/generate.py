"""Generate pydantic models from `infer.py` / `keys.py` profiles.

    python scripts/ddb_models/generate.py [--profile .ddb_profile/dev.json] [--keys .ddb_profile/dev_keys.json]

Writes (all marked GENERATED, never hand-edited; refinements live in `models/overrides.py`):
    src/mathbank_rest/models/ddb/<ctx>.py     one DdbItem subclass per item type + a discriminated union
    src/mathbank_rest/models/docs/content.py  S3 JSON documents (release / catalogue snapshots)
    src/mathbank_rest/models/docs/offload.py  JSON of attributes offloaded to S3 (`<attr>_ref`)
"""
from __future__ import annotations

import argparse
import builtins
import importlib
import json
import keyword
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[0].parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT.parent / "mathbank-db"))

from infer import merge, new  # noqa: E402
from pydantic import BaseModel  # noqa: E402

MODELS = ROOT / "src" / "mathbank_rest" / "models"
RESERVED = set(dir(BaseModel)) | set(keyword.kwlist) | set(dir(builtins)) | {"model_config", "CTX", "TYPE", "OFFLOADED", "OFFLOAD_DOCS"}
BASE_FIELDS = {"PK", "SK", "type", "version", "ttl"} | {f"GSI{i}{k}" for i in range(1, 6) for k in ("PK", "SK")}
RECORD_KEY = re.compile(r"^[A-Za-z_][A-Za-z0-9_\-. ]{0,60}$")
MAX_DEPTH = 4
HEADER = ('"""GENERATED by scripts/ddb_models/generate.py from the live `{env}` profile - do not edit; add refinements to\n'
          'models/overrides.py and regenerate with `make ddb-models`."""\n')


def camel(s: str) -> str:
    return "".join(p.capitalize() if p.isupper() else p[:1].upper() + p[1:] for p in re.split(r"[^A-Za-z0-9]+", s) if p) or "X"


def field_name(orig: str) -> tuple[str, str | None]:
    """(python name, alias or None)."""
    n = re.sub(r"\W", "_", orig)
    if n[:1].isdigit():
        n = "f_" + n
    if n.startswith("_"):
        n = "f" + n
    if n in RESERVED or n in BASE_FIELDS or n.startswith("model_"):
        n += "_"
    return n, (orig if n != orig else None)


class Emitter:
    def __init__(self) -> None:
        self.blocks: list[str] = []
        self.names: set[str] = set()

    def unique(self, name: str) -> str:
        base, i = name, 2
        while name in self.names:
            name, i = f"{base}{i}", i + 1
        self.names.add(name)
        return name

    def nullable(self, node: dict, tp: str) -> str:
        return tp if tp == "Any" or "null" not in node["kinds"] else f"{tp} | None"

    def expr(self, node: dict, hint: str, depth: int) -> str:
        parts: list[str] = []
        for k in sorted(k for k in node["kinds"] if k != "null"):
            if k == "str":
                fmts = {f for f, c in node["fmt"].items() if c}
                parts.append({"ts": "UtcDateTime", "date": "dt.date", "uuid": "UUID"}.get(next(iter(fmts)), "StrictStr") if len(fmts) == 1 else "StrictStr")
            elif k in ("int", "bool", "float"):
                parts.append({"int": "StrictInt", "bool": "StrictBool", "float": "StrictFloat"}[k])
            elif k == "list":
                item = node["item"]
                parts.append("list[Any]" if item is None or not item["n"] else f"list[{self.nullable(item, self.expr(item, hint + 'Item', depth + 1))}]")
            elif k == "dict":
                parts.append(self.dict_expr(node, hint, depth))
            else:
                parts.append("Any")
        if not parts or "Any" in parts:
            return "Any"
        parts = list(dict.fromkeys(parts))
        if "StrictInt" in parts and "StrictFloat" in parts:
            parts.remove("StrictInt")             # StrictFloat accepts the integral values too
        return " | ".join(parts)

    def dict_expr(self, node: dict, hint: str, depth: int) -> str:
        children, n = node["children"], node["dict_n"]
        if node["mapping"] or not children:
            item = node["item"]
            return "dict[str, Any]" if item is None or not item["n"] else f"dict[str, {self.nullable(item, self.expr(item, hint + 'Value', depth + 1))}]"
        if depth >= MAX_DEPTH or any(not RECORD_KEY.match(k) for k in children):
            merged = new()
            for c in children.values():
                merge(merged, c)
            return f"dict[str, {self.nullable(merged, self.expr(merged, hint + 'Value', depth + 1)) if merged['n'] else 'Any'}]"
        sparse = sum(1 for c in children.values() if c["n"] < 0.5 * n)
        if len(children) >= 6 and sparse > len(children) / 2 and n >= 5:
            return "dict[str, Any]"          # free-form JSON: keys vary per document
        return self.record(node, self.unique(hint), depth)

    def fields(self, node: dict, hint: str, depth: int, skip: set[str] = frozenset(), optional: set[str] = frozenset()) -> list[str]:
        n, lines = node["dict_n"], []
        for orig in sorted(node["children"], key=lambda k: (-(node["children"][k]["n"]), k)):
            if orig in skip:
                continue
            c = node["children"][orig]
            name, alias = field_name(orig)
            required = c["n"] == n and "null" not in c["kinds"] and orig not in optional
            if orig.endswith("_ref") and {"bucket", "key", "sha256"} <= set(c["children"]):
                tp, required = "S3Ref", False
            else:
                tp = self.expr(c, hint + camel(orig), depth + 1)
            if not required and tp != "Any":
                tp = f"{tp} | None"
            if alias:
                default = "Field(alias=%r)" % alias if required else "Field(default=None, alias=%r)" % alias
            else:
                default = "" if required else "None"
            line = f"    {name}: {tp}" + (f" = {default}" if default else "")
            if (not c["vals_overflow"]) and 0 < len(c["vals"]) <= 8 and c["n"] >= 50 and tp.startswith("StrictStr"):
                line += "  # observed: " + " | ".join(sorted(c["vals"]))
            lines.append(line)
        return lines

    def record(self, node: dict, name: str, depth: int) -> str:
        body = "\n".join(self.fields(node, name, depth)) or "    pass"
        self.blocks.append(f"class {name}(JsonDoc):\n{body}\n")
        return name


def key_pattern(stats: dict | None) -> str | None:
    """Regex for one key attribute from its observed segment shapes (see keys.py)."""
    if not stats:
        return None
    alts = []
    for n in sorted(stats["nseg"], key=int):
        parts = []
        for i in range(int(n)):
            classes = stats["pos"].get(f"{n}:{i}", {})
            lits = [c for c in classes if not c.startswith("{")]
            wild = "{*}" in classes or len(classes) > (6 if i == 0 else 3)
            if not wild and i > 0 and any(not re.fullmatch(r"[A-Z][A-Z0-9_]*", c) for c in lits):
                wild = True
            if wild or not classes:
                parts.append("[^#]*")
                continue
            alt = [{"{uuid}": r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}", "{hex}": r"[0-9a-f]{16,}",
                    "{n}": r"-?\d+", "{ts}": r"[^#]+"}.get(c, re.escape(c)) for c in sorted(classes)]
            parts.append("(?:" + "|".join(alt) + ")" if len(alt) > 1 else alt[0])
        alts.append("#".join(parts))
    return "^(?:" + "|".join(alts) + ")$" if len(alts) > 1 else "^" + alts[0] + "$"


def spec_offloads() -> dict[tuple[str, str], tuple[str, ...]]:
    """OFFLOAD maps declared by the migration specs (attributes that may live in S3 even if none did in this env)."""
    out: dict[tuple[str, str], tuple[str, ...]] = {}
    try:
        for m in ("content", "exam", "learner", "live", "media", "staff"):
            mod = importlib.import_module(f"aws.dynamo.specs.{m}")
            for k, v in getattr(mod, "OFFLOAD", {}).items():
                out[(k[0].replace("-", "_"), k[1])] = tuple(v)
    except Exception as e:  # noqa: BLE001
        print("warning: spec OFFLOAD maps not loaded:", e, file=sys.stderr)
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--profile", default=str(ROOT / ".ddb_profile/dev.json"))
    ap.add_argument("--keys", default=str(ROOT / ".ddb_profile/dev_keys.json"))
    a = ap.parse_args()
    prof = json.load(open(a.profile))
    keys = json.load(open(a.keys)) if Path(a.keys).exists() else {}
    offloads = spec_offloads()
    header = HEADER.format(env=prof["env"])

    # ------------------------------------------------------------ S3 JSON documents
    docs = {"content": (Emitter(), []), "offload": (Emitter(), [])}
    doc_alias: dict[str, str] = {}
    for fam in sorted(prof["s3"]):
        parts = fam.split(":")
        if fam.startswith("offload:"):
            kind, base = "offload", "Offload" + camel(parts[1]) + camel(parts[2]) + camel(parts[3])
        elif fam.startswith("content:"):
            kind, base = "content", "".join(camel(p) for p in parts[1:])
            base = "ReleaseSnapshot" if base == "Release" else base
        else:
            continue
        em, aliases = docs[kind]
        t = em.expr(prof["s3"][fam], base, 0)
        if t in em.names:
            doc_alias[fam] = t
        else:
            name = em.unique(base)
            aliases.append(f"{name}: TypeAlias = {t}\n")
            doc_alias[fam] = name
    doc_imports = ("from __future__ import annotations\n\nimport datetime as dt\nfrom typing import Any, TypeAlias\nfrom uuid import UUID\n\n"
                   "from pydantic import Field, StrictBool, StrictFloat, StrictInt, StrictStr  # noqa: F401\n\nfrom mathbank_rest.models.base import JsonDoc, UtcDateTime  # noqa: F401\n\n\n")
    for kind, (em, aliases) in docs.items():
        (MODELS / "docs" / f"{kind}.py").write_text(header + doc_imports + "\n\n".join(em.blocks + aliases) + "\n")
    reg = ["from mathbank_rest.models.docs import content as _c, offload as _o  # noqa: F401\n", "DOC_MODELS = {"]
    for fam, name in sorted(doc_alias.items()):
        reg.append(f"    {fam!r}: {'_c' if fam.startswith('content:') else '_o'}.{name},")
    reg.append("}")
    (MODELS / "docs" / "registry.py").write_text(header + "\n".join(reg) + "\n")

    # ------------------------------------------------------------ items
    summary = []
    for ctx, types in prof["tables"].items():
        if not types:
            continue
        em, cc = Emitter(), camel(ctx)
        class_names: list[str] = []
        used_docs: set[str] = set()
        for t in sorted(types):
            node, cls = types[t], em.unique(cc + camel(t))
            class_names.append(cls)
            ch = node["children"]
            offl = sorted({k[:-4] for k in ch if k.endswith("_ref")} | set(offloads.get((ctx, t), ())))
            odocs = {}
            for attr in offl:
                fam = f"offload:{ctx.replace('_', '-')}:{t}:{attr}"
                if fam in doc_alias:
                    odocs[attr] = doc_alias[fam]
                    used_docs.add(doc_alias[fam])
            fld = em.fields(node, cls, 0, skip=BASE_FIELDS, optional=set(offl))
            for attr in offl:                    # spec-declared offloads not seen in this environment
                for suffix, tp in (("", "Any | None = None"), ("_ref", "S3Ref | None = None")):
                    nm, alias = field_name(attr + suffix)
                    if not any(line.startswith(f"    {nm}:") for line in fld):
                        fld.append(f"    {nm}: {tp}" if not alias else f"    {nm}: {tp.split(' = ')[0]} = Field(default=None, alias={alias!r})")
            kp = keys.get(ctx, {}).get(t, {})
            body = [f'    type: Literal["{t}"] = "{t}"']
            for attr in ("PK", "SK"):
                pat = key_pattern(kp.get(attr))
                if pat:
                    body.append(f"    {attr}: str = Field(pattern={pat!r})")
            if offl:
                body.append(f"    OFFLOADED: ClassVar[frozenset[str]] = frozenset({set(offl)!r})")
            if odocs:
                body.append("    OFFLOAD_DOCS: ClassVar[dict[str, Any]] = {" + ", ".join(f"{k!r}: {v}" for k, v in odocs.items()) + "}")
            gsi = sorted(k for k in ch if re.fullmatch(r"GSI\d(PK|SK)", k))
            em.blocks.append(f'class {cls}(DdbItem, ctx="{ctx}", item_type="{t}"):\n' + "\n".join(body + fld) + "\n")
            if not gsi:
                pass
        union = ", ".join(class_names)
        em.blocks.append(f'{cc}Item = Annotated[Union[{union}], Field(discriminator="type")]\nITEM_MODELS = [{union}]\n')
        imp = ""
        if used_docs:
            imp = "from mathbank_rest.models.docs.offload import (  # noqa: F401\n" + "".join(f"    {d},\n" for d in sorted(used_docs)) + ")\n"
        mod = (header + "from __future__ import annotations\n\nimport datetime as dt\nfrom typing import Annotated, Any, ClassVar, Literal, Union\nfrom uuid import UUID\n\n"
               "from pydantic import Field, StrictBool, StrictFloat, StrictInt, StrictStr  # noqa: F401\n\nfrom mathbank_rest.models.base import DdbItem, JsonDoc, S3Ref, UtcDateTime  # noqa: F401\n" + imp + "\n\n"
               + "\n\n".join(em.blocks))
        (MODELS / "ddb" / f"{ctx}.py").write_text(mod)
        summary.append(f"{ctx}: {len(class_names)} item models")
    print("\n".join(summary))


if __name__ == "__main__":
    main()
